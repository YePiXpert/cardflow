// 规范化 JSON 与 input_hash：README"规范化 JSON 与 input_hash"的测试向量、
// tests/protocol/test_adapter.py 的全部向量、F-18 哈希 ea990327…1ee8，以及由 Python 引擎生成的
// 161 个浮点向量（ECMAScript Number::toString 与 Python repr 的最短往返写法逐字一致）。
import 'dart:convert';

import 'package:cardflow_domain/cardflow_domain.dart';
import 'package:cardflow_domain/testing.dart';
import 'package:test/test.dart';

import 'support/python_float_vectors.dart';
import 'support/repo.dart';

String canon(Object? value) => utf8.decode(canonicalJson(value));

/// 浮点记号 → 解析后的值（Python 测试里的 float 字面量在 JSON 里就是这些记号）。
Object? number(String token) => parseJsonText(token);

void main() {
  group('README / test_adapter.py vectors', () {
    test('objects sort by UTF-16 code units, arrays keep their order', () {
      expect(
        canon(<String, Object?>{
          'b': 1,
          'a': <Object?>[true, false, null],
        }),
        '{"a":[true,false,null],"b":1}',
      );
      expect(
        canon(<String, Object?>{'金额': '卡A', 'z': '€'}),
        '{"z":"€","金额":"卡A"}',
      );
      // U+1F600（D83D DE00）排在 U+FB01 之前：UTF-16 序，不是码点序
      expect(canon(<String, Object?>{'😀': 1, 'ﬁ': 2}), '{"😀":1,"ﬁ":2}');
    });

    test('string escapes are those of json.dumps(ensure_ascii=False)', () {
      expect(
        canon('"\\/\b\f\n\r\t\x00\x1f\x7f\u2028'),
        r'"\"\\/\b\f\n\r\t\u0000\u001f'
        '\x7f\u2028"',
      );
    });

    test('integers are exact decimal, beyond 64 bits too', () {
      expect(canon(9223372036854775807), '9223372036854775807');
      expect(canon(-9223372036854775807 - 1), '-9223372036854775808');
      expect(canon(BigInt.from(10).pow(30)), '1000000000000000000000000000000');
      expect(canon(number('-0')), '0');
    });

    test('non-integers follow ECMAScript Number.prototype.toString', () {
      const vectors = <String, String>{
        '10.0': '10',
        '0.5': '0.5',
        '-0.0': '0',
        '1e-6': '0.000001',
        '1e-7': '1e-7',
        '1e21': '1e+21',
        '1e20': '100000000000000000000',
        '123.456': '123.456',
        '5e-324': '5e-324',
        '1.7976931348623157e308': '1.7976931348623157e+308',
        '295147905179352825856.0': '295147905179352830000', // 2.0 ** 68
        '9.999999999999997e22': '9.999999999999997e+22',
        '1e23': '1e+23',
        '9.999999999999997e-7': '9.999999999999997e-7',
        '333333333.3333333': '333333333.3333333',
        '999999999999999900000.0': '999999999999999900000',
      };
      vectors.forEach((token, expected) {
        expect(canon(number(token)), expected, reason: token);
      });
    });

    test('161 float vectors generated by the Python engine', () {
      expect(pythonFloatVectors, hasLength(161));
      for (final (token, expected) in pythonFloatVectors) {
        expect(canon(number(token)), expected, reason: token);
      }
    });

    test(
      'non-JSON values, lone surrogates and non-string keys are refused',
      () {
        for (final value in <Object?>[
          '\ud800',
          <String, Object?>{'a': '\udc00x'},
          <Object?, Object?>{1: 'x'},
          DateTime(2026),
          LocalDate(2026, 1, 1),
        ]) {
          expect(
            () => canonicalJson(value),
            throwsA(isA<ProtocolError>()),
            reason: '$value',
          );
        }
      },
    );
  });

  group('protocol_input_hash', () {
    test('F-18 is pinned at ea990327…1ee8 (README, test_adapter.py)', () {
      expect(protocolInputHash(f18Input()), f18InputHash);
    });

    test(
      'member order and whitespace do not matter, values and array order do',
      () {
        final doc = f18Input();
        final pretty = const JsonEncoder.withIndent('    ').convert(doc);
        expect(protocolInputHash(parseJsonText(pretty)), f18InputHash);
        final reordered = <String, Object?>{
          for (final key in doc.keys.toList().reversed) key: doc[key],
        };
        expect(protocolInputHash(reordered), f18InputHash);
        final changed = f18Input();
        obj(changed['request'])['amount_minor'] = 1000001;
        expect(protocolInputHash(changed), isNot(f18InputHash));
        final swapped = f18Input();
        swapped['cards'] = arr(swapped['cards']).reversed.toList();
        expect(protocolInputHash(swapped), isNot(f18InputHash));
      },
    );

    test(
      'an integral time_limit_s token hashes like its integer (10.0 and 10)',
      () {
        final a = f18Input();
        final b = deepCopyJson(f18Input())! as Map<String, Object?>;
        obj(b['options'])['time_limit_s'] = number('10.0');
        expect(protocolInputHash(b), protocolInputHash(a));
      },
    );
  });
}
